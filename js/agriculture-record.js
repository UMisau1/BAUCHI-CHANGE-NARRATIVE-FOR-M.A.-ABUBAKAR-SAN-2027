/* =========================================================
   FILTER BY YEAR
========================================================= */

function getAgricultureRecordsByYear(year) {

    return agricultureRecords.filter(
        item =>
            item.year === Number(year)
    );

}


/* =========================================================
   FILTER BY CATEGORY
========================================================= */

function getAgricultureRecordsByCategory(category) {

    return agricultureRecords.filter(
        item =>
            item.category.toLowerCase() ===
            String(category).toLowerCase()
    );

}


/* =========================================================
   SEARCH
========================================================= */

function searchAgricultureRecords(keyword) {

    const searchTerm =
        String(keyword)
            .toLowerCase()
            .trim();


    if (!searchTerm) {

        return agricultureRecords;

    }


    return agricultureRecords.filter(
        item => {

            const searchableText = `

                ${item.year}
                ${item.category}
                ${item.title}
                ${item.description}
                ${item.figure}
                ${item.status}
                ${item.source}
                ${item.verification}

            `.toLowerCase();


            return searchableText.includes(
                searchTerm
            );

        }
    );

}


