/* =========================================================
   HELPER FUNCTIONS
========================================================= */

function getDirectivesByYear(year) {

    return executiveDirectives.filter(
        item => item.year === Number(year)
    );

}


function getDirectivesByCategory(category) {

    return executiveDirectives.filter(
        item =>
            item.category.toLowerCase() ===
            String(category).toLowerCase()
    );

}


function searchExecutiveDirectives(keyword) {

    const searchTerm =
        String(keyword).toLowerCase().trim();

    if (!searchTerm) {
        return executiveDirectives;
    }

    return executiveDirectives.filter(item =>

        item.title.toLowerCase().includes(searchTerm) ||

        item.category.toLowerCase().includes(searchTerm) ||

        item.subject.toLowerCase().includes(searchTerm) ||

        item.action.toLowerCase().includes(searchTerm)

    );

}


