/* =========================================================
   HELPER FUNCTIONS
========================================================= */

function getLegislativeLawsByYear(year) {

    return legislativeLaws.filter(
        law => law.year === Number(year)
    );

}


function getLegislativeLawsByCategory(category) {

    return legislativeLaws.filter(
        law =>
            law.category.toLowerCase() ===
            String(category).toLowerCase()
    );

}


function searchLegislativeLaws(keyword) {

    const searchTerm =
        String(keyword)
            .toLowerCase()
            .trim();

    if (!searchTerm) {
        return legislativeLaws;
    }

    return legislativeLaws.filter(law => {

        const text = `
            ${law.lawNo}
            ${law.year}
            ${law.category}
            ${law.title}
            ${law.status}
        `.toLowerCase();

        return text.includes(searchTerm);

    });

}


